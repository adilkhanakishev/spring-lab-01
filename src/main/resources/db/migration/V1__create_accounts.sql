CREATE TABLE audit_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 message VARCHAR(255) NOT NULL
);

CREATE TABLE author (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100) NOT NULL, country VARCHAR(100));
CREATE TABLE tag (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(50) NOT NULL UNIQUE);
CREATE TABLE book (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(120) NOT NULL, genre VARCHAR(20) NOT NULL, year INTEGER NOT NULL, archived BOOLEAN NOT NULL, created_at TIMESTAMP WITH TIME ZONE, version BIGINT NOT NULL, author_id BIGINT REFERENCES author(id));
CREATE TABLE book_tag (book_id BIGINT NOT NULL REFERENCES book(id), tag_id BIGINT NOT NULL REFERENCES tag(id), added_at TIMESTAMP WITH TIME ZONE NOT NULL, PRIMARY KEY(book_id,tag_id));
